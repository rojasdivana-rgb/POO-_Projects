package edu.divana.rojas.calculadora.process;

/**
 * Clase que contiene la operación aritmética de resta.
 */
public class Resta {
    /**
     * Realiza la sustracción de dos números.
     * @param n1 Minuendo.
     * @param n2 Sustraendo.
     * @return La diferencia entre n1 y n2.
     */
    public static double realizarOperacion(double n1, double n2) {
        return n1 - n2;
    }
}