package edu.divana.rojas.calculadora.process;

/**
 * Esta clase contiene la operación básica de suma.
 */
public class Suma {
    /**
     * Realiza la suma de dos números reales.
     * @param n1 Primer sumando.
     * @param n2 Segundo sumando.
     * @return El resultado de n1 + n2.
     */
    public static double realizarOperacion(double n1, double n2) {
        return n1 + n2;
    }
}