package edudivanarojas.actividad2.process;

/**
 * Clase que realiza la operación de resta aritmética.
 * Utiliza el operador - para restar dos números.
 */
public class Resta {
    /**
     * Realiza la resta de dos números.
     *
     * @param a el minuendo
     * @param b el sustraendo
     * @return la diferencia de a - b
     */
    public static double realizarOperacion(double a, double b) {
        return a - b;
    }
}
