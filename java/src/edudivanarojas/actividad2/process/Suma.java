package edudivanarojas.actividad2.process;

/**
 * Clase que realiza la operación de suma aritmética.
 * Utiliza el operador + para sumar dos números.
 */
public class Suma {
    /**
     * Realiza la suma de dos números.
     *
     * @param a el primer número
     * @param b el segundo número
     * @return la suma de a + b
     */
    public static double realizarOperacion(double a, double b) {
        return a + b;
    }
}
